/* 
算術演算子
*/
//加算
let add = 10 + 5;
console.log(add);

//文字列の連結
let str = "java"+"script";
console.log(str);

let result1 = 3 + 3;
let result2 = "3"+"3";

console.log(result1);
console.log(result2);

//減算
let sub = 10 - 5;
console.log(sub);

//乗算(multiplication)
let mul = 10 * 5;
console.log(mul);

//除算(division)
let div = 10/5;
console.log(div);//2

//インクリメント(increment)
let incr = 10;
incr++;//現在の値に1を加える
console.log(incr);//11

//デクリメント(decrement)
let decr = 10;
decr--; //現在の値から1を引く
console.log(decr);

